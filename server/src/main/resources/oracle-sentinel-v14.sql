CREATE TABLE sentinel_match_sample (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id       VARCHAR2(128 CHAR) NOT NULL,
    monitor_id    NUMBER NOT NULL REFERENCES sentinel_monitor(id) ON DELETE CASCADE,
    channel_id    CHAR(36),
    sample_time   TIMESTAMP NOT NULL,
    match_count   NUMBER(19) NOT NULL,
    samples_json  CLOB,
    complete      NUMBER(1) DEFAULT 1 NOT NULL
)
